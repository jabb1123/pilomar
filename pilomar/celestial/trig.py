def rotate_xyz_on_z_axis(x, y, z, angle):
    """Rotate x,y cooordinates by an angle around z axis.
    Z = ZENITH - NADIR axis. ZENITH is +ve. NADIR is -ve.
    X = EAST - WEST axis.    EAST is +ve.   WEST is -ve.
    Y = NORTH - SOUTH axis.  NORTH is +ve.  SOUTH is -ve.
    """
    try:
        hyp = math.sqrt(x * x + y * y)
        orig_angle = math.degrees(math.atan2(y, x))
        new_angle = orig_angle - angle
        new_x = math.cos(math.radians(new_angle)) * hyp
        new_y = math.sin(math.radians(new_angle)) * hyp
    except Exception as e:  # pylint: disable=broad-except
        print("pilomartrig: RotateXYZonZaxis(", x, y, z, angle, ") Failed:", e)
        new_x = new_y = None
    return new_x, new_y, z


# ------------------------------------------------------------------


def rotate_xyz_on_x_axis(x, y, z, angle) -> Tuple[float, float, float]:
    """Rotate y,z cooordinates by an angle around x axis.
    Z = ZENITH - NADIR axis. ZENITH is +ve. NADIR is -ve.
    X = EAST - WEST axis.    EAST is +ve.   WEST is -ve.
    Y = NORTH - SOUTH axis.  NORTH is +ve.  SOUTH is -ve.
    """
    try:
        hyp = math.sqrt(y * y + z * z)
        orig_angle = math.degrees(math.atan2(z, y))
        new_angle = orig_angle + angle
        new_y = math.cos(math.radians(new_angle)) * hyp
        new_z = math.sin(math.radians(new_angle)) * hyp
    except Exception as e:  # pylint: disable=broad-except
        print("pilomartrig: RotateXYZonXaxis(", x, y, z, angle, ") Failed:", e)
        x = new_y = new_z = 0.0
    return x, new_y, new_z


