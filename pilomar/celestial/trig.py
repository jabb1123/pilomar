def compound_angle(alt, az):
    """Given alt,az, return compound angle from 0,0 to the point."""
    r_comp = math.degrees(
        math.acos(math.cos(math.radians(az)) * math.cos(math.radians(alt)))
    )  # Compound angle from Alt & Az combined.
    return r_comp


