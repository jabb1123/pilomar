def display_hms(h, m, s, length=12, rounding=1):
    """Display HMS values in human readable format.
    h = hours.
    m = minutes.
    s = seconds (can be decimal).
    length = length of returned string.
    rounding = number of decimals precision in the seconds value."""
    hs = str(int(h))
    if len(hs) < 2:
        hs = hs.rjust(2)
    ms = str(int(m))
    if len(ms) < 2:
        ms = ms.rjust(2)
    ss = str(round(s, rounding))
    if len(ss.split(".", maxsplit=1)[0]) < 2:
        ss = " " + ss
    dh = hs + "h " + ms + "m " + ss + "s"
    dh = dh.rjust(length, " ")[(-1 * length) :]
    return dh


